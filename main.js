// Menu bar app that turns copied text (e.g. from PDFs) into plain text without line breaks.
const { app, BrowserWindow, Menu, Tray, clipboard, globalShortcut, shell, systemPreferences } = require('electron')
const fs = require('fs')
const path = require('path')
const { MODES, cleanText } = require('./clean')
const { copySelection } = require('./copy-selection')

const isMac = process.platform === 'darwin'

// The first free one wins. Control+Command+C is "Cmd+C plus one finger" and is not used by macOS.
const SHORTCUTS = [
  { accelerator: 'Control+Command+C', label: '⌃⌘C' },
  { accelerator: 'Control+Option+Command+C', label: '⌃⌥⌘C' }
]

// Clipboard contents that must never be rewritten: files, images and passwords from password managers.
const SKIP_TYPES = /^text\/uri-list$|^image\/|org\.nspasteboard\.(Concealed|Transient|AutoGenerated)Type/

const DEFAULT_SETTINGS = { mode: MODES.SINGLE_LINE, autoClean: false, welcomed: false }

let settings = { ...DEFAULT_SETTINGS }
let tray = null
let mainWindow = null
let shortcut = null
let lastSeenText = null
let busy = false
let trusted = false

const settingsFile = () => path.join(app.getPath('userData'), 'settings.json')

function loadSettings () {
  try {
    settings = { ...DEFAULT_SETTINGS, ...JSON.parse(fs.readFileSync(settingsFile(), 'utf8')) }
  } catch {
    settings = { ...DEFAULT_SETTINGS }
  }
}

function updateSettings (changes) {
  settings = { ...settings, ...changes }
  try {
    fs.mkdirSync(path.dirname(settingsFile()), { recursive: true })
    fs.writeFileSync(settingsFile(), JSON.stringify(settings, null, 2))
  } catch (error) {
    console.error('Could not save settings', error)
  }
  buildTrayMenu()
}

const isAccessibilityTrusted = (prompt = false) =>
  !isMac || systemPreferences.isTrustedAccessibilityClient(prompt)

const openAccessibilitySettings = () =>
  shell.openExternal('x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility')

// Returns the clipboard text if it is safe to replace, otherwise null.
async function readReplaceableText () {
  const [item] = await clipboard.read()
  const types = item ? item.types : []
  if (!types.includes('text/plain') || types.some((type) => SKIP_TYPES.test(type))) return null
  const text = await clipboard.readText()
  if (!text) return null
  return { text, styled: types.includes('text/html') || types.includes('text/rtf') }
}

async function writeCleaned (text) {
  const cleaned = cleanText(text, settings.mode)
  await clipboard.writeText(cleaned)
  lastSeenText = cleaned
}

function flashTray (title) {
  if (!tray) return
  tray.setTitle(title)
  setTimeout(() => tray && tray.setTitle(''), 1200)
}

async function copyAndClean () {
  if (busy) return
  if (!isAccessibilityTrusted()) {
    isAccessibilityTrusted(true)
    openAccessibilitySettings()
    return
  }

  busy = true
  try {
    const copied = await copySelection()
    const content = copied && await readReplaceableText()
    if (!content) {
      shell.beep()
      return
    }
    await writeCleaned(content.text)
    flashTray(' ✓')
  } finally {
    busy = false
  }
}

// Optional legacy behaviour: clean everything copied with plain Cmd+C.
async function watchClipboard () {
  if (busy) return
  busy = true
  try {
    const content = await readReplaceableText()
    if (!content) return
    // First run only remembers what was already there, so launching the app does not touch the clipboard.
    if (lastSeenText === null) {
      lastSeenText = content.text
      return
    }
    if (content.text === lastSeenText && !content.styled) return
    await writeCleaned(content.text)
  } catch (error) {
    console.error('Clipboard watch failed', error)
  } finally {
    busy = false
  }
}

function registerShortcut () {
  for (const candidate of SHORTCUTS) {
    if (globalShortcut.register(candidate.accelerator, copyAndClean)) {
      shortcut = candidate
      return
    }
  }
  console.error('None of the shortcuts could be registered')
}

function buildTrayMenu () {
  if (!tray) return
  const modeItem = (label, mode) => ({
    label,
    type: 'radio',
    checked: settings.mode === mode,
    click: () => updateSettings({ mode })
  })

  tray.setContextMenu(Menu.buildFromTemplate([
    {
      label: shortcut ? `Copy & Clean: ${shortcut.label}` : 'Shortcut unavailable',
      enabled: false
    },
    ...(trusted ? [] : [{
      label: 'Allow Accessibility Access…',
      click: () => {
        isAccessibilityTrusted(true)
        openAccessibilitySettings()
      }
    }]),
    { type: 'separator' },
    modeItem('Remove All Line Breaks', MODES.SINGLE_LINE),
    modeItem('Keep Paragraphs', MODES.PARAGRAPHS),
    modeItem('Only Remove Styles', MODES.PLAIN),
    { type: 'separator' },
    {
      label: 'Also Clean Every ⌘C Copy',
      type: 'checkbox',
      checked: settings.autoClean,
      click: (item) => {
        lastSeenText = null
        updateSettings({ autoClean: item.checked })
      }
    },
    ...(isMac || process.platform === 'win32' ? [{
      label: 'Open at Login',
      type: 'checkbox',
      checked: app.getLoginItemSettings().openAtLogin,
      click: (item) => app.setLoginItemSettings({ openAtLogin: item.checked })
    }] : []),
    { type: 'separator' },
    { label: 'How It Works…', click: showWindow },
    { label: 'Quit', role: 'quit' }
  ]))
}

function showWindow () {
  if (mainWindow) {
    mainWindow.show()
    mainWindow.focus()
    return
  }

  mainWindow = new BrowserWindow({
    width: 720,
    height: 640,
    title: 'Paste without Line Breaks',
    icon: path.join(__dirname, 'icon.png')
  })
  mainWindow.loadFile('index.html', { query: { shortcut: shortcut ? shortcut.label : '' } })

  // Links open in the default browser instead of inside the app.
  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    shell.openExternal(url)
    return { action: 'deny' }
  })
  mainWindow.webContents.on('will-navigate', (event, url) => {
    event.preventDefault()
    shell.openExternal(url)
  })
  mainWindow.on('closed', () => { mainWindow = null })

  if (isMac) app.focus({ steal: true })
}

if (!app.requestSingleInstanceLock()) {
  app.quit()
} else {
  app.on('second-instance', showWindow)

  // Keep running in the menu bar when the window is closed.
  app.on('window-all-closed', () => {})

  app.on('will-quit', () => globalShortcut.unregisterAll())

  app.whenReady().then(() => {
    if (isMac) app.dock.hide()
    loadSettings()

    tray = new Tray(path.join(__dirname, 'assets', 'trayTemplate.png'))
    tray.setToolTip('Paste without Line Breaks')
    registerShortcut()
    trusted = isAccessibilityTrusted()
    buildTrayMenu()

    setInterval(() => {
      if (settings.autoClean) watchClipboard()
      // Refresh the menu once the user grants (or revokes) the Accessibility permission.
      const nowTrusted = isAccessibilityTrusted()
      if (nowTrusted !== trusted) {
        trusted = nowTrusted
        buildTrayMenu()
      }
    }, 500)

    if (!settings.welcomed) {
      showWindow()
      updateSettings({ welcomed: true })
    }
  })
}
